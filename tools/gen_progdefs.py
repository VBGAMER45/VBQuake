"""
gen_progdefs.py - writes src/progdefs.bas from ref/WinQuake/progdefs.q1:
globalvars_t and entvars_t as VB types with the C struct layout (every
member 4 bytes, vec3_t 12), plus a constant with each field's offset in
4-byte units (GOFS_<name>, EOFS_<name>).

  python -I tools/gen_progdefs.py

The progs memory is a Long array; pr_edict.bas lays these types over it, so
the engine reads ev(e).origin where the C reads e->v.origin. C's int pad[28]
at the start of globalvars_t becomes null_, ret and parm(0 To 7) (OFS_NULL,
OFS_RETURN, OFS_PARM0..7), so builtins can pass their vector parameters
ByRef. entvars_t is padded with ext() to EDICT_STRIDE Longs, room for the
fields a progs.dat adds after the system ones.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EDICT_STRIDE = 512          # Longs per edict's fields (C: progs->entityfields)

VBTYPE = {"int": "Long", "float": "Single", "string_t": "Long", "func_t": "Long", "vec3_t": "vec3_t"}
SIZE = {"int": 1, "float": 1, "string_t": 1, "func_t": 1, "vec3_t": 3}
RESERVED = {"time", "self", "main", "size", "message", "model", "frame", "target", "owner", "team",
            "items", "skin", "enemy", "chain", "solid"}


def parse(text, name):
    bodies = {n: body for body, n in re.findall(r"typedef struct\s*\{([^}]*)\}\s*(\w+);", text)}
    body = bodies[name]
    fields = []
    for m in re.finditer(r"(\w+)\s+(\w+)(\[(\d+)\])?;", body):
        fields.append((m.group(1), m.group(2), int(m.group(4)) if m.group(4) else None))
    return fields


def vbname(n):
    return n


def main():
    with open(os.path.join(ROOT, "ref", "WinQuake", "progdefs.q1")) as f:
        text = f.read()
    gfields = parse(text, "globalvars_t")
    efields = parse(text, "entvars_t")
    crc = re.search(r"PROGHEADER_CRC\s+(\d+)", text).group(1)

    out = ['Attribute VB_Name = "progdefs"',
           "' progdefs.bas - generated by tools/gen_progdefs.py from progdefs.q1; do not edit.",
           "' The system globals and entity fields that progs.dat shares with the",
           "' engine, with the C struct layout; pr_edict.bas lays them over the progs",
           "' memory (pr_global_struct(0), ev(e)).",
           "'",
           "' QuakeVB: a Visual Basic 6 port of the Quake source release.",
           "' Copyright (C) 1996-1997 Id Software, Inc.  Licensed under the GNU GPL v2.",
           "Option Explicit", "",
           "Public Const PROGHEADER_CRC As Long = %s" % crc,
           "Public Const EDICT_STRIDE As Long = %d          ' Longs per edict (C: entityfields)" % EDICT_STRIDE,
           ""]

    # globals
    out.append("Public Type globalvars_t")
    ofs = 0
    consts = []
    for typ, name, count in gfields:
        if name == "pad":
            assert count == 28
            out += ["    null_ As Long                  ' OFS_NULL",
                    "    ret As vec3_t                  ' OFS_RETURN",
                    "    parm(0 To 7) As vec3_t         ' OFS_PARM0 .. OFS_PARM7"]
            ofs = 28
            continue
        out.append("    %s As %s" % (vbname(name), VBTYPE[typ]))
        consts.append("Public Const GOFS_%s As Long = %d" % (name, ofs))
        ofs += SIZE[typ]
    out.append("End Type")
    out.append("Public Const GLOBALVARS_SIZE As Long = %d          ' Longs" % ofs)
    out.append("")
    out += consts
    out.append("")

    # entity fields
    out.append("Public Type entvars_t")
    ofs = 0
    consts = []
    for typ, name, count in efields:
        out.append("    %s As %s" % (vbname(name), VBTYPE[typ]))
        consts.append("Public Const EOFS_%s As Long = %d" % (name, ofs))
        ofs += SIZE[typ]
    out.append("    ext(0 To %d) As Long          ' fields the progs define after these" % (EDICT_STRIDE - ofs - 1))
    out.append("End Type")
    out.append("Public Const ENTVARS_SIZE As Long = %d             ' Longs of system fields" % ofs)
    out.append("")
    out += consts
    out.append("")

    with open(os.path.join(ROOT, "src", "progdefs.bas"), "w", newline="\r\n") as f:
        f.write("\n".join(out) + "\n")
    print("globalvars_t: %d fields, entvars_t: %d fields (%d Longs), stride %d"
          % (len(gfields), len(efields), ofs, EDICT_STRIDE))


if __name__ == "__main__":
    main()
