"""
gen_printf_tests.py - writes tests/printf_cases.bas: vsprintf cases with the
output of C's printf (Python's % formatting follows it). Float arguments
are rounded to 32 bits first, as a C float is before it is promoted.

  python -I tools/gen_printf_tests.py
"""
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


FLOATS = [0.0, 1.0, -1.0, 0.1, 1.09, 100.0, 3.14159, 1e10, -0.5, 1e-7, 123456.789, 0.5, 1.5, 2.5, 33.333,
          -273.15, 4096.0, 0.04, -0.04, 999999.5, 1e-5, 0.0001, 123456789.0]
CASES = []
for fmt in ["%f", "%4.2f", "%5.1f", "%.0f", "%g", "%e", "%10.3f", "%-8.2f|", "%+.1f"]:
    for x in FLOATS:
        CASES.append((fmt, "f", f32(x)))
for fmt in ["%i", "%d", "%3i", "%-5i|", "%05i", "%x", "%X", "%u", "%+d", "%.3d"]:
    for v in [0, 7, -5, 255, 65535, 2147483647, -2147483648, 12345]:
        CASES.append((fmt, "i", v))
for fmt in ["%s", "%10s|", "%-10s|", "%.3s"]:
    for v in ["", "abc", "hello world"]:
        CASES.append((fmt, "s", v))
CASES.append(("%c%c%c", "c", (81, 86, 66)))
CASES.append(("100%% done", "n", None))
CASES.append(("%s is %4.1f megs", "sf", ("heap", f32(8.5))))


def vb_str(s):
    return '"' + s.replace('"', '""') + '"'


def c_value(kind, v):
    if kind == "f":
        return "%r" % v
    return str(v)


def main():
    lines = ['Attribute VB_Name = "printf_cases"',
             "' printf_cases.bas - generated by tools/gen_printf_tests.py; do not edit.",
             "' vsprintf against C printf output.",
             "Option Explicit", "",
             "Public Sub RunPrintfCases()"]
    for fmt, kind, v in CASES:
        if kind == "f":
            expect = fmt % v
            call = "vsprintf(%s, Array(CSng(%s)))" % (vb_str(fmt), repr(v) if "e" not in repr(v) else "%.9g" % v)
        elif kind == "i":
            if fmt == "%u":
                expect = fmt % (v & 0xFFFFFFFF)
            elif fmt in ("%x", "%X"):
                expect = fmt % (v & 0xFFFFFFFF)
            else:
                expect = fmt % v
            lit = "&H80000000" if v == -2147483648 else str(v)
            call = "vsprintf(%s, Array(CLng(%s)))" % (vb_str(fmt), lit)
        elif kind == "s":
            expect = fmt % v
            call = "vsprintf(%s, Array(%s))" % (vb_str(fmt), vb_str(v))
        elif kind == "c":
            expect = fmt % tuple(chr(c) for c in v)
            call = "vsprintf(%s, Array(%s))" % (vb_str(fmt), ", ".join("CLng(%d)" % c for c in v))
        elif kind == "n":
            expect = fmt % ()
            call = "vsprintf(%s, Array())" % vb_str(fmt)
        else:
            expect = fmt % v
            call = "vsprintf(%s, Array(%s, CSng(%r)))" % (vb_str(fmt), vb_str(v[0]), v[1])
        lines.append("    CheckStr %s, %s, %s" % (vb_str(fmt + " " + str(v)), call, vb_str(expect)))
    lines.append("End Sub")
    with open(os.path.join(ROOT, "tests", "printf_cases.bas"), "w", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d cases" % len(CASES))


if __name__ == "__main__":
    main()
