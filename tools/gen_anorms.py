"""
gen_anorms.py - writes src/anorms.bas from ref/WinQuake/anorms.h: the 162
vertex normals that an alias model's lightnormalindex picks from
(r_avertexnormals, which r_alias.c fills with #include "anorms.h").

  python -I tools/gen_anorms.py

VB has no array initializers, so the module fills the table in
R_InitVertexNormals, which R_Init calls.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    with open(os.path.join(ROOT, "ref", "WinQuake", "anorms.h")) as f:
        text = f.read()
    normals = re.findall(r"\{\s*([-0-9.]+)\s*,\s*([-0-9.]+)\s*,\s*([-0-9.]+)\s*\}", text)
    if len(normals) != 162:
        raise SystemExit("anorms.h: %d normals, expected 162" % len(normals))

    out = [
        'Attribute VB_Name = "anorms"',
        "' anorms.bas - the vertex normals of alias models (anorms.h, the table",
        "' r_alias.c includes as r_avertexnormals).",
        "' Generated by tools/gen_anorms.py: do not edit.",
        "'",
        "' QuakeVB: a Visual Basic 6 port of the Quake source release.",
        "' Copyright (C) 1996-1997 Id Software, Inc.  Licensed under the GNU GPL v2.",
        "Option Explicit",
        "",
        "Public Const NUMVERTEXNORMALS As Long = 162",
        "",
        "Public r_avertexnormals(0 To NUMVERTEXNORMALS - 1, 0 To 2) As Single",
        "",
        "Private Sub SetNormal(ByVal i As Long, ByVal x As Single, ByVal y As Single, ByVal z As Single)",
        "    r_avertexnormals(i, 0) = x",
        "    r_avertexnormals(i, 1) = y",
        "    r_avertexnormals(i, 2) = z",
        "End Sub",
        "",
        "' (QuakeVB) C initializes the table statically; R_Init calls this",
        "Public Sub R_InitVertexNormals()",
    ]
    for i, (x, y, z) in enumerate(normals):
        out.append("    SetNormal %d, %s!, %s!, %s!" % (i, x, y, z))
    out.append("End Sub")

    with open(os.path.join(ROOT, "src", "anorms.bas"), "w", newline="\r\n") as f:
        f.write("\n".join(out) + "\n")
    print("anorms.bas: %d normals" % len(normals))


if __name__ == "__main__":
    main()
